"""Writes groups.dl: the lattice of groups, the groups that each role allows and the derivation of the group of each space, copied verbatim from
batches/0019/states.dl.

nf.dl needs only that part of states.dl (lines 14 to 25, 33 to 79 and 128 to 144 of the file); the rest computes the dimension of the gauge group and
the class of each state under a generator, and two of its aggregates make Souffle warn that a variable occurs once. Including the whole file would
carry those warnings into this batch, and editing the file would change a committed batch, so the lines that are needed are copied. CI runs this
script and fails if groups.dl changes.
Usage: make_groups.py [OUT]     (default: groups.dl next to this file)
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "0019", "states.dl")
RANGES = [(14, 25), (33, 79), (128, 144)]  # inclusive, 1-based
HEADER = """// SPDX-FileCopyrightText: 2026 Ian Douglas Lawrence Norman McLean
// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by make_groups.py from batches/0019/states.dl, lines 14-25, 33-79 and 128-144, verbatim. Do not edit: CI regenerates it and compares.
"""


def main(argv):
    with open(SRC) as f:
        lines = f.read().split("\n")
    out = HEADER
    for a, b in RANGES:
        out += "\n".join(lines[a - 1 : b]) + "\n\n"
    path = argv[0] if argv else os.path.join(HERE, "groups.dl")
    with open(path, "w") as f:
        f.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
